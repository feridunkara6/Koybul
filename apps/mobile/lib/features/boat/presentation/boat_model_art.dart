/// Marka+model metninden KATI eşleşme. Bulunamazsa null → tür çizimi.
BoatArtEntry? boatModelArt({String? brand, String? model}) {
  final String raw = '${brand ?? ''} ${model ?? ''}'.toLowerCase();
  if (raw.trim().isEmpty) return null;
  final String compact =
      raw.replaceAll(',', '.').replaceAll(RegExp(r'[^a-z0-9.]'), '');
  final Iterable<String> nums = RegExp(r'\d+(?:\.\d+)?')
      .allMatches(compact)
      .map((RegExpMatch m) => m.group(0)!);
  for (final BoatArtEntry e in kBoatModelCatalog) {
    if (!e.families.any((String f) => compact.contains(f))) continue;
    for (final String found in nums) {
      final String intPart = found.split('.').first;
      if (e.numbers.contains(found) || e.numbers.contains(intPart)) {
        return e;
      }
    }
  }
  return null;
}

